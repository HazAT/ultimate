import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { batch, deadline, debounce, every, nextTurn, pace, within } from '../lib/timers.shared.ts'

beforeEach(() => vi.useFakeTimers())
afterEach(() => vi.useRealTimers())

it('debounces to the last call, flushes a pending call at once and cancels', () => {
  const fn = vi.fn<() => void>()
  const typed = debounce(100, fn)
  typed()
  vi.advanceTimersByTime(80)
  typed()
  vi.advanceTimersByTime(80)
  expect(fn).not.toHaveBeenCalled()
  vi.advanceTimersByTime(20)
  expect(fn).toHaveBeenCalledTimes(1)
  typed.flush()
  expect(fn).toHaveBeenCalledTimes(1)
  typed()
  typed.flush()
  expect(fn).toHaveBeenCalledTimes(2)
  typed()
  typed.cancel()
  vi.runAllTimers()
  expect(fn).toHaveBeenCalledTimes(2)
})

it('batches a burst into one call timed from its first change', () => {
  const fn = vi.fn<() => void>()
  const write = batch(100, fn)
  write()
  vi.advanceTimersByTime(80)
  write()
  vi.advanceTimersByTime(20)
  expect(fn).toHaveBeenCalledTimes(1)
  write()
  write.cancel()
  vi.runAllTimers()
  expect(fn).toHaveBeenCalledTimes(1)
})

it('expires a deadline unless cancelled, and repeats a schedule until stopped', () => {
  const expire = vi.fn<() => void>()
  deadline(50, expire)
  deadline(50, expire)()
  const tick = vi.fn<() => void>()
  const stop = every(10, tick)
  vi.advanceTimersByTime(50)
  stop()
  vi.advanceTimersByTime(50)
  expect(expire).toHaveBeenCalledTimes(1)
  expect(tick).toHaveBeenCalledTimes(5)
})

it('settles within its deadline, rejects after it and clears it on abort', async () => {
  await expect(within(100, Promise.resolve(1), () => new Error('late'))).resolves.toBe(1)
  expect(vi.getTimerCount()).toBe(0)
  const late = within(100, new Promise(() => {}), () => new Error('late'))
  vi.advanceTimersByTime(100)
  await expect(late).rejects.toThrow('late')
  const controller = new AbortController()
  const dropped = within(100, new Promise(() => {}), () => new Error('late'), controller.signal)
  controller.abort()
  expect(vi.getTimerCount()).toBe(0)
  vi.advanceTimersByTime(100)
  await expect(Promise.race([dropped, Promise.resolve('pending')])).resolves.toBe('pending')
})

it('paces after its delay, rejects on abort and refuses an aborted signal', async () => {
  const beat = pace(100)
  vi.advanceTimersByTime(100)
  await expect(beat).resolves.toBeUndefined()
  const controller = new AbortController()
  const stopped = pace(100, controller.signal)
  controller.abort(new Error('stopped'))
  await expect(stopped).rejects.toThrow('stopped')
  expect(vi.getTimerCount()).toBe(0)
  await expect(pace(100, controller.signal)).rejects.toThrow('stopped')
})

it('runs the next turn after the current task', () => {
  const fn = vi.fn<() => void>()
  nextTurn(fn)
  expect(fn).not.toHaveBeenCalled()
  vi.runAllTimers()
  expect(fn).toHaveBeenCalledTimes(1)
})
